/**
 * Turn .cache/off-us.jsonl (from extract-off.ts) into foods/products/**.yaml.
 *
 *   pnpm shard:off
 *   pnpm shard:off --in .cache/off-us.jsonl --limit 500 --out /tmp/preview
 *
 * Shard layout: foods/products/<gtin[2:4]>/<gtin[4:6]>.yaml — ~1k products per file
 * for US UPCs. Files are rewritten wholesale each run so git diffs show real changes.
 * Each file is a YAML list of Food records (schema/food.schema.json).
 */
import { createReadStream, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { createInterface } from 'node:readline';
import { stringify } from 'yaml';
import {
  CACHE, ROOT, loadRefs, makeOffAllergenMatcher, makeOffCategoryMatcher,
  parseServing, toGtin14, gtinAliases, round, slug, type Food,
} from './lib.ts';

const args = process.argv.slice(2);
const opt = (name: string) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : undefined; };
const input = opt('in') ?? resolve(CACHE, 'off-us.jsonl');
const limit = opt('limit') ? Number(opt('limit')) : Infinity;
const outDir = resolve(opt('out') ?? resolve(ROOT, 'foods/products'));

const { nutrients, units, allergens, categories } = loadRefs();
const nutrientByOff = new Map(nutrients.filter((n) => n.off).map((n) => [n.off!, n]));
const matchCategories = makeOffCategoryMatcher(categories);
const matchAllergens = makeOffAllergenMatcher(allergens);

type Row = Record<string, any>;
type Shard = Map<string, Food[]>;
const shards: Shard = new Map();
const unmatchedTags = new Map<string, number>();
let read = 0, kept = 0, skipped = { gtin: 0, nutrients: 0, dup: 0 };
const seen = new Set<string>();

const rl = createInterface({ input: createReadStream(input), crlfDelay: Infinity });
for await (const line of rl) {
  if (!line.trim()) continue;
  if (++read > limit) break;
  const row: Row = JSON.parse(line);
  const food = toFood(row);
  if (!food) continue;
  if (seen.has(food.gtin!)) { skipped.dup++; continue; }
  seen.add(food.gtin!);
  const key = `${food.gtin!.slice(2, 4)}/${food.gtin!.slice(4, 6)}`;
  if (!shards.has(key)) shards.set(key, []);
  shards.get(key)!.push(food);
  kept++;
}

rmSync(outDir, { recursive: true, force: true });
let maxFile = { key: '', n: 0 };
for (const [key, foods] of [...shards].sort()) {
  foods.sort((a, b) => a.gtin!.localeCompare(b.gtin!));
  const file = resolve(outDir, `${key}.yaml`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `# Open Food Facts products, US, GTIN prefix ${key.replace('/', '')}. Generated by scripts/shard-products.ts — do not hand-edit.\n` + stringify(foods, { lineWidth: 0 }));
  if (foods.length > maxFile.n) maxFile = { key, n: foods.length };
}

console.log(`read ${read.toLocaleString()}, kept ${kept.toLocaleString()} into ${shards.size} files (largest ${maxFile.key}: ${maxFile.n})`);
console.log(`skipped: bad barcode ${skipped.gtin}, no mappable nutrients ${skipped.nutrients}, duplicate ${skipped.dup}`);
const top = [...unmatchedTags].sort((a, b) => b[1] - a[1]).slice(0, 15);
if (top.length) console.log('top OFF category tags with no OYL category (add to categories.yaml):\n  ' + top.map(([t, n]) => `${t} (${n})`).join('\n  '));

function toFood(row: Row): Food | null {
  const gtin = toGtin14(row.code);
  if (!gtin) { skipped.gtin++; return null; }

  const nut = parseJson<any[]>(row.nutriments) ?? [];
  const per100: Record<string, number> = {};
  const perServing: Record<string, number> = {};
  for (const item of nut) {
    const def = nutrientByOff.get(item?.name);
    if (!def) continue;
    const v100 = num(item['100g']);
    const vServ = num(item['serving']);
    if (v100 != null) per100[def.id] = convert(def.id, v100 * def.scale);
    if (vServ != null) perServing[def.id] = convert(def.id, vServ * def.scale);
  }
  // Must have at least calories or the macro trio to be useful.
  if (!('energy' in per100) && !('fat' in per100 && 'carbohydrate' in per100 && 'protein' in per100)) { skipped.nutrients++; return null; }

  // serving_quantity is OFF's parsed number (g or ml); the unit comes from the printed text.
  const parsedServing = parseServing(row.serving_size, units);
  const servingQty = num(row.serving_quantity);
  const serving = servingQty && servingQty > 0
    ? { size: servingQty, unit: parsedServing?.unit ?? (isVolume(row.product_quantity_unit) ? 'ml' as const : 'g' as const) }
    : parsedServing;
  const basis: Food['basis'] = (serving?.unit === 'ml' || isVolume(row.product_quantity_unit)) ? '100ml' : '100g';

  const cats = matchCategories(row.categories_tags);
  if (cats[0] === 'other') for (const t of row.categories_tags ?? []) unmatchedTags.set(t, (unmatchedTags.get(t) ?? 0) + 1);

  const food: Food = {
    id: `off:${gtin}`,
    kind: 'product',
    name: clean(row.name)!,
    ...(clean(row.brands) && { brand: clean(row.brands)!.split(',')[0].trim() }),
    ...(clean(row.brand_owner) && { brand_owner: clean(row.brand_owner)! }),
    ...(clean(row.generic_name) && { description: clean(row.generic_name)! }),
    gtin,
    ...(gtinAliases(String(row.code), gtin).length && { gtin_aliases: gtinAliases(String(row.code), gtin) }),
    ...(clean(row.quantity) && { quantity: clean(row.quantity)! }),
    ...(num(row.product_quantity) && !isVolume(row.product_quantity_unit) && { net_grams: round(num(row.product_quantity)!, 2) }),
    basis,
    ...(serving && {
      serving: {
        size: round(serving.size, 2), unit: serving.unit,
        ...(clean(row.serving_size) && { description: clean(row.serving_size)! }),
        ...(num(row.product_quantity) && serving.size > 0 && { per_container: round(num(row.product_quantity)! / serving.size, 1) }),
      },
    }),
    nutrients: per100,
    ...(Object.keys(perServing).length && { nutrients_per_serving: perServing }),
    ...(clean(row.ingredients_text) && { ingredients: { text: clean(row.ingredients_text)!, ...ingredientList(row.ingredients) } }),
    ...(matchAllergens(row.allergens_tags).length && { allergens: matchAllergens(row.allergens_tags) }),
    ...(matchAllergens(row.traces_tags).length && { traces: matchAllergens(row.traces_tags) }),
    categories: cats,
    ...(labels(row.labels_tags).length && { labels: labels(row.labels_tags) }),
    ...(num(row.nova_group) && { nova: num(row.nova_group)! }),
    ...(/^[a-e]$/.test(row.nutriscore_grade ?? '') && { nutriscore: row.nutriscore_grade }),
    ...(images(row) && { images: images(row)! }),
    source: {
      name: 'off',
      id: String(row.code),
      url: `https://world.openfoodfacts.org/product/${row.code}`,
      ...(num(row.last_modified_t) && { modified: new Date(num(row.last_modified_t)! * 1000).toISOString().slice(0, 10) }),
      ...(num(row.completeness) != null && { completeness: round(num(row.completeness)!, 2) }),
      license: 'ODbL-1.0',
    },
  };
  return food;
}

/** OFF reports alcohol as % by volume; store grams per 100 ml (ethanol density 0.789). */
function convert(id: string, v: number): number {
  if (id === 'alcohol') v = v * 0.789;
  return round(v, 3);
}

function ingredientList(json: unknown): { list?: string[] } {
  const parsed = parseJson<any[]>(json);
  if (!Array.isArray(parsed)) return {};
  const list = parsed.map((i) => clean(i?.text)).filter((x): x is string => !!x);
  return list.length ? { list } : {};
}

function labels(tags: string[] | null): string[] {
  return [...new Set((tags ?? []).filter((t) => t.startsWith('en:')).map(slug))].slice(0, 20);
}

function images(row: Row): Food['images'] | null {
  const imgs = parseJson<any[]>(row.images);
  if (!Array.isArray(imgs) || !imgs.length) return null;
  const code = String(row.code);
  const folder = code.length > 8 ? code.replace(/^(\d{3})(\d{3})(\d{3})(\d+)$/, '$1/$2/$3/$4') : code;
  const out: NonNullable<Food['images']> = {};
  for (const kind of ['front', 'nutrition', 'ingredients'] as const) {
    const sel = imgs.find((i) => i?.key === `${kind}_en`) ?? imgs.find((i) => typeof i?.key === 'string' && i.key.startsWith(`${kind}_`));
    if (sel?.imgid != null) out[kind] = `https://images.openfoodfacts.org/images/products/${folder}/${sel.imgid}.400.jpg`;
  }
  return Object.keys(out).length ? out : null;
}

function isVolume(u: unknown): boolean { return typeof u === 'string' && /^(ml|mL|l|L|cl|fl ?oz)$/.test(u.trim()); }
function clean(s: unknown): string | null { if (typeof s !== 'string') return null; const t = s.replace(/\s+/g, ' ').trim(); return t.length ? t : null; }
function num(v: unknown): number | null { if (v === null || v === undefined || v === '') return null; const n = Number(v); return Number.isFinite(n) ? n : null; }
function parseJson<T>(v: unknown): T | null { if (v == null) return null; if (typeof v !== 'string') return v as T; try { return JSON.parse(v) as T; } catch { return null; } }

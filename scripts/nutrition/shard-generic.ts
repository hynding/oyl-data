/**
 * Turn .cache/usda.jsonl (from extract-usda.ts) into nutrition/foods/generic/<dataset>/<category>.yaml.
 *
 *   pnpm shard:usda
 *   pnpm shard:usda --in .cache/usda.jsonl --out /tmp/preview
 *   pnpm shard:usda --force                # overwrite even if the record count drops > 20%
 *
 * One file per (dataset, source category) — a few dozen per dataset, each a reviewable
 * YAML list sorted by name. The same food often appears in Foundation, SR Legacy and
 * FNDDS; we keep one per normalized description, preferring foundation > sr_legacy > survey.
 */
import fg from 'fast-glob';
import { createReadStream, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { createInterface } from 'node:readline';
import { stringify } from 'yaml';
import {
  CACHE, DOMAIN_DIR, args, opt, loadRefs, makeFdcCategoryMatcher, refreshGuard, round, slug, type Food, type Nutrient,
} from './lib.ts';

const input = opt('in') ?? resolve(CACHE, 'usda.jsonl');
const outDir = resolve(opt('out') ?? resolve(DOMAIN_DIR, 'foods/generic'));
const DATASET_RANK: Record<string, number> = { foundation: 0, sr_legacy: 1, survey: 2 };
const FDC_UNIT: Record<string, Nutrient['unit']> = { G: 'g', MG: 'mg', UG: 'mcg', KCAL: 'kcal' };

const { nutrients, categories } = loadRefs();
const matchCategory = makeFdcCategoryMatcher(categories);
/** fdc nutrient id → our nutrient, with list order = preference order (first present wins). */
const byFdc = new Map<number, { def: Nutrient; rank: number }>();
for (const def of nutrients) {
  const ids = def.fdc == null ? [] : Array.isArray(def.fdc) ? def.fdc : [def.fdc];
  ids.forEach((id, rank) => byFdc.set(id, { def, rank }));
}

/** SR Legacy writes branded entries as "McDONALD'S, Big Mac". Peel an all-caps leading brand off. */
const BRAND_CASE: Record<string, string> = {
  "MCDONALD'S": "McDonald's", KFC: 'KFC', IHOP: 'IHOP', "DENNY'S": "Denny's", "APPLEBEE'S": "Applebee's",
  "T.G.I. FRIDAY'S": "T.G.I. Friday's", "CARRABBA'S ITALIAN GRILL": "Carrabba's Italian Grill", "PAPA JOHN'S": "Papa John's",
  "WENDY'S": "Wendy's", "ARBY'S": "Arby's", "CHICK-FIL-A": 'Chick-fil-A', "DOMINO'S": "Domino's", "KELLOGG'S": "Kellogg's",
  "CAMPBELL'S": "Campbell's", 'TACO BELL': 'Taco Bell', 'BURGER KING': 'Burger King', 'PIZZA HUT': 'Pizza Hut', 'SUBWAY': 'Subway',
};
type Row = {
  fdc_id: number; dataset: string; data_type: string; description: string; category: string | null;
  nutrients: { id: number; amount: number; unit: string }[];
  portions: { amount: number | null; unit: string | null; description: string | null; modifier: string | null; grams: number | null }[] | null;
};

const byKey = new Map<string, { food: Food; dataset: string; category: string | null; rank: number }>();
const unmatched = new Map<string, number>();
let read = 0, skippedNoEnergy = 0, dedup = 0;

const rl = createInterface({ input: createReadStream(input), crlfDelay: Infinity });
for await (const line of rl) {
  if (!line.trim()) continue;
  read++;
  const row: Row = JSON.parse(line);
  const food = toFood(row);
  if (!food) { skippedNoEnergy++; continue; }
  const key = normalizeName(food.name, food.brand);
  const rank = DATASET_RANK[row.dataset] ?? 9;
  const existing = byKey.get(key);
  if (existing && existing.rank <= rank) { dedup++; continue; }
  if (existing) dedup++;
  byKey.set(key, { food, dataset: row.dataset, category: row.category, rank });
}

// Group into files: <dataset>/<category-slug>.yaml
const files = new Map<string, Food[]>();
for (const { food, dataset, category } of byKey.values()) {
  const file = `${dataset}/${slug(category ?? 'uncategorized') || 'uncategorized'}`;
  if (!files.has(file)) files.set(file, []);
  files.get(file)!.push(food);
}

refreshGuard(outDir, [...byKey.values()].map((v) => v.food.id), args.includes('--force'));
for (const d of fg.sync(Object.keys(DATASET_RANK), { cwd: outDir, onlyDirectories: true, absolute: true })) rmSync(d, { recursive: true, force: true });

for (const [file, foods] of [...files].sort()) {
  foods.sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
  const path = resolve(outDir, `${file}.yaml`);
  mkdirSync(dirname(path), { recursive: true });
  const [dataset, cat] = file.split('/');
  writeFileSync(path, `# USDA FoodData Central ${dataset}, category "${cat}". Generated by scripts/nutrition/shard-generic.ts — do not hand-edit.\n` + stringify(foods, { lineWidth: 0 }));
}

console.log(`read ${read.toLocaleString()}, kept ${byKey.size.toLocaleString()} into ${files.size} files; skipped ${skippedNoEnergy} without energy/macros, ${dedup} duplicates across datasets`);
const top = [...unmatched].sort((a, b) => b[1] - a[1]).slice(0, 15);
if (top.length) console.log('top FDC/WWEIA categories with no OYL category (add to categories.yaml):\n  ' + top.map(([t, n]) => `${t} (${n})`).join('\n  '));

function toFood(row: Row): Food | null {
  // Nutrients: per 100 g, in our units; honour the preference order for ids that map to the same nutrient.
  const chosen = new Map<string, { rank: number; value: number }>();
  for (const n of row.nutrients ?? []) {
    const hit = byFdc.get(n.id);
    if (!hit) continue;
    const unit = FDC_UNIT[(n.unit ?? '').toUpperCase()];
    if (unit !== hit.def.unit || n.amount == null || n.amount < 0) continue;
    const prev = chosen.get(hit.def.id);
    if (!prev || hit.rank < prev.rank) chosen.set(hit.def.id, { rank: hit.rank, value: n.amount });
  }
  const per100: Record<string, number> = {};
  for (const def of nutrients) { const c = chosen.get(def.id); if (c) per100[def.id] = round(c.value, 3); }
  if (!('energy' in per100) && !('fat' in per100 && 'carbohydrate' in per100 && 'protein' in per100)) return null;

  const { name, brand } = splitBrand(row.description);
  const portions = portionsOf(row.portions);
  let category = matchCategory(row.category);
  if (/\b(fast food|restaurant)\b/i.test(row.description)) category = 'restaurant';
  if (category === 'other') unmatched.set(row.category ?? '(none)', (unmatched.get(row.category ?? '(none)') ?? 0) + 1);

  return {
    id: `fdc:${row.fdc_id}`,
    kind: 'generic',
    name,
    ...(brand && { brand }),
    basis: '100g',
    ...(portions.length && { portions }),
    nutrients: per100,
    categories: [category],
    source: {
      name: 'fdc',
      id: String(row.fdc_id),
      dataset: row.dataset,
      url: `https://fdc.nal.usda.gov/food-details/${row.fdc_id}/nutrients`,
      license: 'CC0',
    },
  };
}

/** "1 cup, chopped (91 g)" from FDC's amount / measure unit / modifier / description columns. */
function portionsOf(list: Row['portions']): NonNullable<Food['portions']> {
  const out: NonNullable<Food['portions']> = [];
  const seen = new Set<string>();
  for (const p of list ?? []) {
    if (!p.grams || p.grams <= 0) continue;
    const unit = (p.unit ?? '').trim();
    const hasUnit = unit && unit !== 'undetermined';
    const amount = p.amount && p.amount > 0 ? p.amount : null;
    let description = clean(p.description) ?? '';
    if (!description) {
      const parts = [amount != null && hasUnit ? `${trimNum(amount)} ${unit}` : hasUnit ? unit : '', clean(p.modifier) ?? ''].filter(Boolean);
      description = parts.join(', ');
    } else if (clean(p.modifier) && !/^\d+$/.test(p.modifier!) && !description.includes(p.modifier!)) {
      description = `${description}, ${clean(p.modifier)}`;
    }
    if (!description) continue;
    const key = description.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ description, grams: round(p.grams, 2), ...(amount != null && hasUnit && { amount, unit: slug(unit) }) });
  }
  return out;
}

function splitBrand(description: string): { name: string; brand?: string } {
  const m = description.match(/^([A-Z][A-Za-z0-9'&.\- ]{2,}?),\s+(.+)$/);
  if (!m) return { name: clean(description) ?? description };
  const letters = m[1].replace(/[^A-Za-z]/g, '');
  const upper = letters.replace(/[^A-Z]/g, '').length;
  if (letters.length < 3 || upper / letters.length < 0.8) return { name: clean(description) ?? description }; // "Banana, raw" stays
  const raw = m[1].trim();
  const brand = BRAND_CASE[raw.toUpperCase()] ?? raw.toLowerCase().replace(/(^|[\s\-.])([a-z])/g, (s) => s.toUpperCase());
  return { name: clean(m[2])!, brand };
}

function normalizeName(name: string, brand?: string): string {
  return `${brand ?? ''}|${name}`.toLowerCase().replace(/[^a-z0-9|]+/g, ' ').trim();
}
function clean(s: unknown): string | null { if (typeof s !== 'string') return null; const t = s.replace(/\s+/g, ' ').trim(); return t.length ? t : null; }
function trimNum(n: number): string { return Number.isInteger(n) ? String(n) : String(round(n, 3)); }
